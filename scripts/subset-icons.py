"""Run with Python + fontTools; --check verifies the committed icon subset."""
import json
from pathlib import Path
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
font_dir = root / "node_modules/remixicon/fonts"
glyphs = json.loads((font_dir / "remixicon.glyph.json").read_text(encoding="utf-8"))
names, prefixes = set(), set()
for folder in ("app", "components", "lib", "src"):
    for path in (root / folder).rglob("*"):
        if path.suffix not in (".ts", ".tsx", ".js", ".jsx", ".css", ".scss"):
            continue
        source = path.read_text(encoding="utf-8")
        names.update(re.findall(r"\bri-([a-z0-9]+(?:-[a-z0-9]+)*)", source))
        prefixes.update(re.findall(r"\bri-([a-z0-9-]+)\$\{", source))

points = sorted(int(value["unicode"][3:-1], 16) for name, value in glyphs.items()
                if name in names or any(name.startswith(prefix) for prefix in prefixes))
assert points, "No icons found; refusing to produce an empty font"
css_path = root / "app/css/remixicon-subset.css"
font_path = css_path.with_suffix(".woff")
css = """/* Generated by scripts/subset-icons.py; full Remix Icon remains the fallback. */
@font-face {
  font-family: 'remixicon';
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url('./remixicon-subset.woff') format('woff');
  unicode-range: %s;
}
""" % ", ".join(f"U+{point:X}" for point in points)

if "--check" in sys.argv:
    assert css_path.read_text(encoding="utf-8") == css, "Run python scripts/subset-icons.py"
else:
    font = TTFont(font_dir / "remixicon.ttf", recalcTimestamp=False)
    options = subset.Options()
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=points)
    subsetter.subset(font)
    font.flavor = "woff"
    font.save(font_path)
    css_path.write_text(css, encoding="utf-8", newline="\n")
    css_path.with_suffix(".LICENSE").write_bytes((font_dir.parent / "License").read_bytes())

output = TTFont(font_path)
original = TTFont(font_dir / "remixicon.ttf")
assert set(output.getBestCmap()) == set(points), "Icon coverage mismatch"
for point, name in output.getBestCmap().items():
    original_name = original.getBestCmap()[point]
    assert output["glyf"][name].getCoordinates(output["glyf"]) == original["glyf"][original_name].getCoordinates(original["glyf"]), f"Icon shape changed: {point:X}"
    assert output["hmtx"][name] == original["hmtx"][original_name], f"Icon spacing changed: {point:X}"
assert font_path.stat().st_size < (font_dir / "remixicon.woff2").stat().st_size / 4
print(f"Icon subset verified: {len(points)} glyphs, {font_path.stat().st_size:,} bytes")
