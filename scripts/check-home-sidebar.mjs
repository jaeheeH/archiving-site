import assert from 'node:assert/strict';

const base = process.argv[2] || 'http://localhost:3002';
const response = await fetch(base);
assert.equal(response.status, 200);
const page = await response.text();
assert(page.includes('제안 보내기') && page.includes('메일 앱 열기') && page.includes('주소 복사'));
assert(page.includes('mailto:archbehind@gmail.com?subject=ARCH.B%20%EC%A0%9C%EC%95%88'));
assert(page.includes('aria-label="제안 받을 메일 주소"'));
const discovery = page.match(/<section class="news-archive-discovery"[\s\S]*?<\/section>/)?.[0];
assert(discovery?.includes('작가 아카이브'), 'Home shows the artist archive');
assert(page.indexOf(discovery) > page.indexOf('aria-label="최신 주요 뉴스"'), 'The artist introduction follows the top stories');
assert(discovery.includes('href="/artists"') && discovery.includes('작가 보러가기'), 'The artist introduction links to the artist archive');
const paths = ['/artists'];
const artwork = page.match(/<section class="news-section news-home-art"[\s\S]*?<\/section>/)?.[0];
const references = page.match(/<section class="news-section news-home-reference-section"[\s\S]*?<\/section>/)?.[0];
assert(artwork?.includes('<img') && artwork.includes('href="/art"'), 'Home shows an artwork and links to the full art archive');
const works = [...artwork.matchAll(/<li\b[^>]*data-flow-copy="original"[^>]*>([\s\S]*?)<\/li>/g)];
assert(works.length > 0 && works.length <= 9 && works.every(work => work[1].includes('<img')), 'Home shows up to nine artwork thumbnails');
assert.equal(new Set([...artwork.matchAll(/href="(\/art\/[^"?]+)"/g)].map(match => match[1])).size, works.length, 'Artwork rows link to distinct works');
assert(artwork.includes('aria-keyshortcuts="Space"') && artwork.includes('id="home-art-flow-help"'), 'Artwork motion remains controllable with the keyboard');
const repeatedWorks = [...artwork.matchAll(/<li\b[^>]*data-flow-copy="repeat"[^>]*>([\s\S]*?)<\/li>/g)];
assert.equal(repeatedWorks.length, works.length, 'Each artwork has one visual loop copy');
assert(repeatedWorks.every(work => /aria-hidden="true"/.test(work[0]) && /tabindex="-1"/i.test(work[1])), 'Loop copies do not create duplicate keyboard stops');
assert(references?.includes('href="/references"'), 'Home shows references with a link to all sites');
assert(!artwork.includes('news-flow-toggle') && !references.includes('news-flow-toggle'), 'The visible flow buttons are removed from both sections');
assert(references.includes('aria-keyshortcuts="Space"'), 'Reference motion remains controllable with the keyboard');
assert(artwork.includes(discovery) && page.indexOf(artwork) < page.indexOf(references), 'The artist introduction sits inside Artwork, followed by references');
const sites = [...references.matchAll(/<li\b[^>]*data-flow-copy="original"[^>]*>([\s\S]*?)<\/li>/g)];
assert(sites.length > 0 && sites.length <= 9, 'Home keeps reference discovery to nine sites');
assert(sites.every(site => /href="https?:\/\//.test(site[1]) && site[1].includes('target="_blank"') && site[1].includes('rel="noopener noreferrer"')), 'Reference links open the actual sites safely in a new tab');
const topics = [...page.matchAll(/<section class="news-section news-topic-section"[\s\S]*?<\/section>/g)];
assert(topics.length > 0 && topics.at(-1).index < page.indexOf(artwork), 'Topic article lists precede artwork and reference discovery');
assert(topics.every(topic => { const count = (topic[0].match(/class="news-topic-story"/g) || []).length; return count > 0 && count <= 3; }), 'Every topic keeps up to three article links');
assert(topics.some(topic => topic[0].includes('class="news-topic-summary"')), 'Topic articles include their existing summaries');
assert.equal((page.match(/<h1\b/g) || []).length, 1, 'Home has one page heading');
paths.push(...new Set([...artwork.matchAll(/href="(\/art\/[^"?]+)"/g)].map(match => match[1])));
const sidebar = page.match(/<aside class="news-sidebar news-home-sidebar"[\s\S]*?<\/aside>/)?.[0];
assert(sidebar && !sidebar.includes('news-archive-discovery') && !sidebar.includes('news-sources'), 'The home sidebar keeps exploration short');
for (const path of paths) {
  const result = await fetch(new URL(path, base));
  assert.equal(result.status, 200, `Discovery link ${path}`);
}
console.log(`Home discovery checks passed: articles with summaries, artist archive CTA, ${works.length} artworks, ${sites.length} reference sites, ${topics.length} topic lists and a short sidebar.`);
