import assert from 'node:assert/strict';
import { matchesSearch,normalizeSearch } from '../lib/search-text';
import { searchPage } from '../lib/resource-search';
import { validateCuration,curationDocument } from '../lib/curation-input';
import type { Resource } from '../lib/resource';
import { readSaveIntent } from '../lib/save-intent';
const row=(id: string,title: string,type: Resource['type']='artwork',searchText=''):Resource => ({id,title,type,searchText,description:'검증된 설명',image:null,url:`/art/${id}`,source:'기관',tags:['유채']});
const resources=[row('monet-1','수련','artwork','클로드 모네 Claude Monet'),row('monet-2','붉은 스카프','artwork','클로드 모네 Claude Monet'),row('manet','모네 가족','artwork','에두아르 마네'),row('monet','클로드 모네','artist')];
assert.equal(searchPage(resources,{q:'모네',type:'artwork'}).total,3);
assert.equal(searchPage(resources,{q:'클로드모네',type:'artwork'}).total,2);
assert.equal(searchPage(resources,{q:'CLAUDE MONET 유채'}).total,2);
assert.equal(searchPage(resources,{q:'수련 유채'}).items[0].id,'monet-1');
assert.ok(matchesSearch('ＡＩ 공간',['AI','공 간']));
assert.equal(normalizeSearch('클 로드　모네'),'클로드모네');
const many=Array.from({length:85},(_,i)=>row(String(i),`자료 ${i}`));
assert.equal(searchPage(many,{page:4}).items.length,13);
assert.equal(searchPage(many,{page:999}).page,4);
assert.equal(searchPage(resources,{q:['모네','없는 이름'],type:['artwork','post'],page:['1','2']}).total,3);
const intent={type:'artwork',id:'monet-1',returnTo:'/search?q=모네&type=artwork&page=2',createdAt:1000};
assert.deepEqual(readSaveIntent(intent,2000),intent);
assert.equal(readSaveIntent({...intent,createdAt:2001},2000),null);
assert.equal(readSaveIntent(intent,700000),null);
assert.equal(readSaveIntent({...intent,returnTo:'//external.example'},2000),null);
assert.equal(readSaveIntent({...intent,type:'unknown'},2000),null);
assert.equal(searchPage(many,{q:'없는 이름'}).total,0);
assert.equal(searchPage(resources,{q:'모네'}).items[0].title,'클로드 모네');
const candidates=Array.from({length:6},(_,i)=>row(String(i),`빛과 공간 자료 ${i}`,i<3 ? 'artwork':'post'));
const draft={title:'빛과 공간을 함께 읽는 여섯 가지 시선',summary:'공간에 들어오는 빛은 사물을 바라보는 방식을 바꿉니다. 확인된 자료를 따라 작품의 색과 건축의 표면을 함께 살펴보며, 서로 다른 작업 사이에서 연결할 수 있는 관점을 찾아봅니다.',items:candidates.map(r=>({key:`${r.type}:${r.id}`,reason:'이 자료는 빛과 공간이라는 주제를 살펴볼 때 참고할 수 있는 확인된 내용입니다. 제공된 제목과 설명에 근거하여 서로 다른 작업의 시선을 연결합니다.'})),closing:'각 자료의 상세 화면에서 출처를 확인하고, 자신이 진행하는 작업에 필요한 관점을 골라보세요.'};
assert.equal(validateCuration(draft,candidates).selected.length,6);
assert.ok(curationDocument(draft,candidates).content.some(node=>node.type==='heading'));
assert.throws(()=>validateCuration({...draft,items:draft.items.map(()=>draft.items[0])},candidates),/중복/);
assert.throws(()=>validateCuration({...draft,items:[{...draft.items[0],key:'post:unknown'},...draft.items.slice(1)]},candidates),/공개 자료/);
const single=candidates.map(r=>({...r,type:'artwork' as const}));
assert.throws(()=>validateCuration({...draft,items:single.map((r,i)=>({...draft.items[i],key:`artwork:${r.id}`}))},single),/두 종류/);
assert.throws(()=>validateCuration(draft,candidates.map((r,i)=>i ? r : {...r,url:'javascript:alert(1)'})),/링크/);
assert.throws(()=>validateCuration({...draft,items:draft.items.slice(0,5)},candidates));
console.log('Search and curation checks passed: bilingual multi-term search, ranking, 24-item pagination, IDs, source links, duplicate and type validation.');
